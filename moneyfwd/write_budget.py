def write_budget():
    gc = get_gs_client()
    sh = gc.open_by_key(SPREADSHEET_ID)
    ws = sh.worksheet(SHEET_NAME)

    updates = []

    # 収入（行7〜、A-G列: A=内訳, B=費目, C=詳細, D=金額, E='', F=開始年, G=終了年）
    print("収入データを書き込み中...")
    for i, (naiyaku, himoku, detail, amount, from_yr, to_yr) in enumerate(INCOME):
        row = 7 + i
        updates.append({'range': f'A{row}:G{row}',
                        'values': [[naiyaku, himoku, detail, amount, '', from_yr, to_yr]]})

    # 投資（行22〜、B-D列 + F-G列）
    print("投資データを書き込み中...")
    for i, (himoku, detail, monthly, from_d, to_d) in enumerate(INVEST):
        row = 22 + i
        updates.append({'range': f'B{row}:G{row}',
                        'values': [[himoku, detail, monthly, '', from_d, to_d]]})

    # 支出（行33〜、A-G列）
    print("支出データを書き込み中...")
    for i, (teki, himoku, detail, amount, cycle, from_d, to_d) in enumerate(EXPENSES):
        row = 33 + i
        updates.append({'range': f'A{row}:G{row}',
                        'values': [[teki, himoku, detail, amount, cycle, from_d, to_d]]})

    ws.batch_update([{'range': u['range'], 'values': u['values']} for u in updates])
    print(f"\n✅ 完了！ {len(updates)}行を書き込みました。")
    print(f"   https://docs.google.com/spreadsheets/d/{SPREADSHEET_ID}")


def init_assets(total_assets: int):
    """
    ライフプランシートに「現在の総資産残高」を設定し、
    貯金額累計（行93）がその残高を起点に積み上がるよう数式を修正する。

    引数:
      total_assets: MoneyForwardの「資産」合計額（円）
    """
    gc = get_gs_client()
    sh = gc.open_by_key(SPREADSHEET_ID)
    ws = sh.worksheet('ライフプランシート')

    # A22: ラベル / C22: 入力値
    ws.update('A22:C22', [['📊 現在の総資産残高（今日時点）', '', total_assets]])
    print(f"  A22に現在資産残高 ¥{total_assets:,} を設定しました")

    # D93: 2026年の貯金累計を「当年の🏦貯金 + 初期資産残高」に変更
    # 従来: =D90  →  変更後: =D90+C22
    ws.update('D93', [['=D90+C22']], value_input_option='USER_ENTERED')
    print("  D93の数式を =D90+C22 に更新しました")
    print("  （E93以降は =E90+D93 のまま自動的に引き継がれます）")

    print(f"\n✅ ライフプランシートの初期資産設定完了")
    print(f"   https://docs.google.com/spreadsheets/d/{SPREADSHEET_ID}")
    print(f"\n  2026年の「貯金額累計」= ¥{total_assets:,} + 2026年の貯金額")
    print(f"  2027年以降は前年累計 + 当年貯金額で積み上がります")


